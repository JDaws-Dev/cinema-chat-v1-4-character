// ── Helpers ──────────────────────────────────────────────

const _objectMap = new Map<string, LayoutObject>();
for (const obj of STORE_LAYOUT.objects) {
  _objectMap.set(obj.id, obj);
}

export function getObjectById(id: string): LayoutObject | undefined {
  return _objectMap.get(id);
}

export function getObjectsByCategory(category: ObjCategory): LayoutObject[] {
  return STORE_LAYOUT.objects.filter(o => o.category === category);
}

function mergeColliderDefaults(
  obj: LayoutObject,
  prefabCollider: LayoutCollider | undefined
): LayoutCollider | undefined {
  if (obj.collider?.enabled === false) return undefined;
  if (!obj.collider && !prefabCollider) return undefined;

  return {
    type: "box",
    enabled: true,
    width: obj.collider?.width ?? prefabCollider?.width ?? obj.w,
    depth: obj.collider?.depth ?? prefabCollider?.depth ?? obj.d,
    offsetX: obj.collider?.offsetX ?? prefabCollider?.offsetX ?? 0,
    offsetZ: obj.collider?.offsetZ ?? prefabCollider?.offsetZ ?? 0,
  };
}

export function resolveLayoutObject(obj: LayoutObject): ResolvedLayoutObject {
  const prefab = resolvePrefabDefinition(obj);

  return {
    ...obj,
    prefabId: obj.prefab || prefab?.id,
    hidden: obj.hidden ?? false,
    locked: obj.locked ?? false,
    layer: obj.layer ?? prefab?.defaultLayer ?? obj.category,
    interaction: obj.interaction ?? prefab?.defaultInteraction,
    collider: mergeColliderDefaults(obj, prefab?.defaultCollider),
  };
}

export function getResolvedLayoutObjects(): ResolvedLayoutObject[] {
  return STORE_LAYOUT.objects.map(resolveLayoutObject);
}

export function getVisibleLayoutObjects(): ResolvedLayoutObject[] {
  return getResolvedLayoutObjects().filter((obj) => !obj.hidden);
}

export function getLayoutColliders(): WorldCollider[] {
  return getVisibleLayoutObjects()
    .filter((obj) => obj.collider?.enabled !== false && obj.collider?.width && obj.collider?.depth)
    .map((obj) => ({
      id: obj.id,
      x: obj.x + (obj.collider?.offsetX ?? 0),
      z: obj.z + (obj.collider?.offsetZ ?? 0),
      hw: (obj.collider?.width ?? 0) / 2,
      hd: (obj.collider?.depth ?? 0) / 2,
    }));
}

export function getLayoutInteractionObjects(): ResolvedLayoutObject[] {
  return getVisibleLayoutObjects().filter((obj) => Boolean(obj.interaction));
}

