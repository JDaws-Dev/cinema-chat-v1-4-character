import { NextResponse } from "next/server";
import fs from "fs";
import path from "path";
import type { StoreLayout } from "@/lib/store-layout";

const LAYOUT_FILE = path.join(process.cwd(), "src/lib/store-layout.ts");

// ── GET: return current layout as JSON ──
export async function GET() {
  try {
    // Dynamic import to always get the latest version
    // We read the file and parse the data from it instead of using the cached module
    const fileContent = fs.readFileSync(LAYOUT_FILE, "utf-8");

    // Extract the objects array from the TypeScript source
    const match = fileContent.match(/objects:\s*\[([\s\S]*?)\],\s*\};/);
    if (!match) {
      // Fallback: import the module directly
      const mod = await import("@/lib/store-layout");
      return NextResponse.json(mod.STORE_LAYOUT);
    }

    // Use the module import for reliable parsing
    const mod = await import("@/lib/store-layout");
    return NextResponse.json(mod.STORE_LAYOUT);
  } catch (err) {
    return NextResponse.json({ error: String(err) }, { status: 500 });
  }
}

// ── POST: update layout by rewriting the source file ──
export async function POST(req: Request) {
  try {
    const layout: StoreLayout = await req.json();

    if (!layout.version || !Array.isArray(layout.objects)) {
      return NextResponse.json({ error: "Invalid layout: needs version and objects array" }, { status: 400 });
    }

    // Generate the TypeScript source code
    const source = generateLayoutSource(layout);

    fs.writeFileSync(LAYOUT_FILE, source, "utf-8");

    return NextResponse.json({ success: true, objectCount: layout.objects.length });
  } catch (err) {
    return NextResponse.json({ error: String(err) }, { status: 500 });
  }
}

